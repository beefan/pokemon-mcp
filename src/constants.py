# Fill A-Z (0x80 - 0x99)
for i in range(26):
    CHAR_MAP[0x80 + i] = chr(ord('A') + i)

# Fill a-z (0xA0 - 0xB9)
for i in range(26):
    CHAR_MAP[0xA0 + i] = chr(ord('a') + i)

# Fill 0-9 (0xF6 - 0xFF)
for i in range(10):
    CHAR_MAP[0xF6 + i] = chr(ord('0') + i)

# Backwards compatibility alias
